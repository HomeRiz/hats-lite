export function errorMessage(code: string, name?: string): string {
  if (code === "opted_out") return stringsPeople.optedOut(name ?? "This person");
  const known = stringsPeople.errors[code];
  if (known) return known;
  return code === "unknown" ? stringsPeople.errors.unknown : stringsPeople.unknownCode(code);
}
